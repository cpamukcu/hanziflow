// Copies the HSK word lists, grammar points and dialogues out of the 学中文 app into data/hsk-content.js.
// Usage: node tools/extract_hsk.mjs "<path to chinese learning app>/index.html"
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) { console.error('Pass the path to the 学中文 index.html'); process.exit(1); }
const html = fs.readFileSync(src, 'utf8');
// Each block is a plain object/array literal: `const NAME = {` … `\n};` or `const NAME=[` … `\n];`
function literal(name, close) {
  const start = html.search(new RegExp('const ' + name + '\\s*='));
  if (start < 0) throw new Error('not found: ' + name);
  const end = html.indexOf('\n' + close, start);
  const body = html.slice(html.indexOf('=', start) + 1, end + 2);
  return new Function('return (' + body + ')')();
}
const out = { lists: literal('DATA', '};'), grammar: literal('LESSONS', '];'), dialogs: literal('DIALOGS', '];') };
const file = '/* data/hsk-content.js — generated by tools/extract_hsk.mjs from the 学中文 app. Do not edit by hand.\n' +
  ' * HSK 2.0 levels 1-5 and HSK 3.0 bands 1-6 as [hanzi, pinyin, meaning], plus grammar points and dialogues. */\n' +
  '(function (g) { g.HF_HSK = ' + JSON.stringify(out) + '; })(typeof window !== "undefined" ? window : globalThis);\n';
fs.writeFileSync(path.join(ROOT, 'data/hsk-content.js'), file);
console.log('wrote data/hsk-content.js', (file.length / 1024).toFixed(0) + ' KB');
